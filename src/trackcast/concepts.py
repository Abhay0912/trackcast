    ("Feature engineering", "One-hot encoding",
     "Train type and railway zone",
     "Few categories with no natural order."),
    ("Feature engineering", "Imputation and scaling",
     "Median imputation with missing-value flags, and standardisation, for the linear models",
     "Linear models need complete inputs on comparable scales; tree models do not."),
    ("Feature engineering", "Interaction term",
     "Lag x slack for the linear models",
     "Slack changes how much of the delay carries over; a linear model cannot find that on its own."),
    # Modelling
